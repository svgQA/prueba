export const groupByPerson = (): GeneralTask => {
  let minStart = new Date(data[0].start);
  let maxEnd = new Date(data[0].end);

  const grouped = data.reduce((acc: any, item) => {
    const userId = item.user.id;
    if (!acc[userId]) {
      acc[userId] = {
        id: item.user.id,
        name: `${item.user.name} ${item.user.surname}`,
        phone: item.user.phone,
        cardId: item.user.cardId,
        tasks: [],
      };
    }

    const startDate = new Date(item.start);
    const endDate = new Date(item.end);

    if (startDate < minStart) {
      minStart = startDate;
    }
    if (endDate > maxEnd) {
      maxEnd = endDate;
    }

    acc[userId].tasks.push({
      start: startDate,
      end: endDate,
      name: item.service.description,
      id: item.id,
      progress: 50,
      type: 'task',
    });
    return acc;
  }, {});

  return {
    startDate: minStart,
    endDate: maxEnd,
    users: Object.values(grouped),
  };
};
